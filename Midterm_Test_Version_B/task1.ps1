param([Parameter(Mandatory=$true)][string]$x)
function e($m){Write-Output $m;exit 1}
if($x -notmatch '^[0-9]+$'){e('ERROR: Student number must contain digits only')}
try{
    $os=Get-CimInstance Win32_OperatingSystem
    $cs=Get-CimInstance Win32_ComputerSystem
    $bios=Get-CimInstance Win32_BIOS
    $cpu=Get-CimInstance Win32_Processor
    $disk=Get-CimInstance Win32_LogicalDisk -Filter 'DriveType=3'
}catch{e('ERROR: Unable to query system information')}
$ds=($disk|measure Size -Sum).Sum
$h=[ordered]@{}
$k1=([char[]](0x68,0x6f,0x73,0x74,0x6e,0x61,0x6d,0x65)-join'')
$k2=([char[]](0x62,0x69,0x6f,0x73,0x5f,0x73,0x65,0x72,0x69,0x61,0x6c)-join'')
$k3=([char[]](0x63,0x70,0x75,0x5f,0x6e,0x61,0x6d,0x65)-join'')
$k4=([char[]](0x6d,0x61,0x6e,0x75,0x66,0x61,0x63,0x74,0x75,0x72,0x65,0x72)-join'')
$k5=([char[]](0x74,0x6f,0x74,0x61,0x6c,0x5f,0x6d,0x65,0x6d,0x5f,0x47,0x42)-join'')
$k6=([char[]](0x64,0x69,0x73,0x6b,0x5f,0x47,0x42)-join'')
$k7=([char[]](0x73,0x74,0x75,0x64,0x65,0x6e,0x74,0x5f,0x69,0x64)-join'')
$h[$k1]=$env:COMPUTERNAME
$h[$k2]=$bios.SerialNumber
$h[$k3]=$cpu.Name
$h[$k4]=$cs.Manufacturer
$h[$k5]=[math]::Round($cs.TotalPhysicalMemory/1GB,2)
$h[$k6]=[math]::Round($ds/1GB,2)
$h[$k7]=$x
$j=$h|ConvertTo-Json -Depth 3
$t=[Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($j))
$t
